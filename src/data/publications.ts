// Helper functions for filtering and searching publications
export const getPublicationsByYear = (year: number): Publication[] => {
  return publications.filter(pub => pub.year === year);
};

export const getPublicationsByCategory = (category: Publication['category']): Publication[] => {
  return publications.filter(pub => pub.category === category);
};

export const getPublicationsByAuthor = (authorName: string): Publication[] => {
  return publications.filter(pub => 
    pub.authors.some(author => 
      author.toLowerCase().includes(authorName.toLowerCase())
    )
  );
};

export const searchPublications = (query: string): Publication[] => {
  const lowercaseQuery = query.toLowerCase();
  return publications.filter(pub => 
    pub.title.toLowerCase().includes(lowercaseQuery) ||
    pub.authors.some(author => author.toLowerCase().includes(lowercaseQuery)) ||
    pub.publisher.toLowerCase().includes(lowercaseQuery)
  );
};

export const getRecentPublications = (limit: number = 5): Publication[] => {
  return publications
    .sort((a, b) => b.year - a.year)
    .slice(0, limit);
};

export const getPublicationYears = (): number[] => {
  const years = [...new Set(publications.map(pub => pub.year))];
  return years.sort((a, b) => b - a);
};